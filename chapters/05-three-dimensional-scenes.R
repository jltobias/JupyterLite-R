# Dependencies: base R graphics. Change log: initial lesson.
terrain <- function(x, y) 100 + 850 * exp(-((x + 700)^2 + (y - 400)^2) / 2400000) +
  550 * exp(-((x - 1300)^2 + (y + 1000)^2) / 1100000)
x <- y <- seq(-3000, 3000, length.out = 51)
z <- outer(x, y, terrain)
flight <- data.frame(t = seq(0, 1, length.out = 100))
flight$x <- -2300 + 4600 * flight$t
flight$y <- 1300 * sin(2 * pi * flight$t)
flight$ground <- terrain(flight$x, flight$y)
flight$altitude <- flight$ground + 140
stopifnot(all(abs(flight$altitude - flight$ground - 140) < 1e-8))
head(flight)
# %%
view <- persp(x, y, z, theta = 35, phi = 30, expand = .65,
              zlim = range(c(z, flight$altitude)), col = "turquoise3", border = NA,
              shade = .35, xlab = "x (m)", ylab = "y (m)", zlab = "Height (m)",
              main = "Fictional terrain and drone route")
route_xy <- trans3d(flight$x, flight$y, flight$altitude, view)
lines(route_xy, col = "darkorange2", lwd = 3)
points(trans3d(flight$x[c(1,100)], flight$y[c(1,100)], flight$altitude[c(1,100)], view),
       pch = c(16,17), col = "navy", cex = 1.3)
legend("topleft", c("Route", "Start", "Finish"), col = c("darkorange2", "navy", "navy"),
       lty = c(1,NA,NA), pch = c(NA,16,17), bty = "n", cex = .8)
# %% [markdown]
# `trans3d()` projects 3D coordinates using the camera matrix returned by `persp()`. It does not
# perform hidden-surface removal for the added route: a line can appear above a ridge that should
# hide it. The interactive WebGL scene uses depth buffering. Both displays need a numeric audit.
# %%
horizontal_step <- sqrt(diff(flight$x)^2 + diff(flight$y)^2)
spatial_step <- sqrt(horizontal_step^2 + diff(flight$altitude)^2)
audit <- data.frame(horizontal_route_m = sum(horizontal_step),
                    three_dimensional_route_m = sum(spatial_step),
                    minimum_clearance_m = min(flight$altitude - flight$ground))
stopifnot(audit$three_dimensional_route_m >= audit$horizontal_route_m)
print(audit)
